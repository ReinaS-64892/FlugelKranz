#!/usr/bin/env python3
"""Generate only used function-table slots from Valve's pinned SDK headers.
Usage: python3 tools/generate-openvr-slots.py /path/to/openvr/headers
"""
import hashlib
import re
import sys
from pathlib import Path
headers = Path(sys.argv[1])
source = (headers / 'openvr_capi.h').read_text()
versions = (headers / 'openvr_api.cs').read_text()
used = {
 'System': ['GetDeviceToAbsoluteTrackingPose', 'GetRawZeroPoseToStandingAbsoluteTrackingPose', 'GetTrackedDeviceClass', 'GetStringTrackedDeviceProperty', 'PollNextEvent', 'AcknowledgeQuit_Exiting'],
 'Applications': ['AddApplicationManifest', 'IdentifyApplication'],
 'Input': ['SetActionManifestPath', 'GetActionSetHandle', 'GetActionHandle', 'UpdateActionState', 'GetDigitalActionData', 'GetAnalogActionData', 'GetPoseActionDataRelativeToNow', 'TriggerHapticVibrationAction'],
 'Overlay': ['CreateOverlay', 'DestroyOverlay', 'WaitFrameSync'],
 'Paths': ['ReadPathBatch', 'WritePathBatch', 'StringToHandle'],
}
lines = ['// Generated by tools/generate-openvr-slots.py. Do not edit.',
         '// Valve OpenVR SDK openvr_capi.h SHA-256: ' + hashlib.sha256(source.encode()).hexdigest(),
         'namespace FlugelKranz.OpenVR;', '', 'internal static class OpenVrSlots', '{']
for interface, methods in used.items():
 version = re.search(r'IVR' + interface + r'_Version = "([^"]+)"', versions)[1]
 body = re.search(r'struct VR_IVR' + interface + r'_FnTable\s*\{(.*?)\n\};', source, re.S)[1]
 names = re.findall(r'OPENVR_FNTABLE_CALLTYPE \*(\w+)\)', body)
 lines += ['    internal static class ' + interface, '    {', '        public const string Version = "FnTable:' + version + '";']
 for method in methods:
  lines += [f'        public const int {method} = {names.index(method)};']
 lines += ['    }']
lines += ['}', '']
Path('src/FlugelKranz.OpenVR/OpenVrSlots.g.cs').write_text('\n'.join(lines))
